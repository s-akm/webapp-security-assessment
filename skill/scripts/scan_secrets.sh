#!/usr/bin/env bash
# scan_secrets.sh — 成果物に秘密情報・個人情報が混入していないかの最終検査
#
#   使い方: ./scan_secrets.sh <報告書のディレクトリ>
#
# 評価の過程では、鍵の値も個人情報も目に入る。手で書き写すつもりがなくても、
# ツールの出力を貼り付けた拍子に混ざる。報告書を書き終えたら必ずこれを通す。
#
# 検出はパターンマッチなので、取りこぼしも誤検出もある。0 件だから安全とは言えない。
# 「明らかな混入を機械的に落とす」ための道具として使う。

set -uo pipefail
DIR="${1:-}"
if [[ -z "$DIR" || ! -d "$DIR" ]]; then
  echo "使い方: $0 <報告書のディレクトリ>" >&2
  exit 1
fi

TARGETS=(--include='*.md' --include='*.txt' --include='*.csv' --include='*.json' --include='*.html')
HITS=0

# 出力を見やすい長さに切る。cut -c はロケールによってバイト単位で動くため、
# 日本語の途中で切ると文字化けする。iconv -c で不完全なバイト列を落として防ぐ。
trim() {
  if command -v iconv >/dev/null 2>&1; then
    cut -c1-200 | iconv -c -f UTF-8 -t UTF-8
  else
    cut -c1-200
  fi
}

check() {
  local label="$1" pattern="$2" note="${3:-}"
  local out
  # grep にパターンを渡すときは必ず -e を使う。'-----BEGIN' のように - で始まる
  # パターンをそのまま渡すと、grep がオプションとして解釈して誤動作する。
  #
  # 検査対象のディレクトリへ移動してから "." を検索する。絶対パスのまま検索すると、
  # 出力の先頭が長いパスで埋まり、肝心の検出内容が表示幅から押し出される。
  out="$(cd "$DIR" && grep -rnIE "${TARGETS[@]}" -e "$pattern" . 2>/dev/null | head -20 || true)"
  if [[ -n "$out" ]]; then
    printf '\n[検出] %s\n' "$label"
    [[ -n "$note" ]] && printf '  %s\n' "$note"
    printf '%s\n' "$out" | sed -E 's/^/  /' | trim
    HITS=$((HITS+1))
  fi
}

echo "検査対象: $DIR"

# --- 鍵・トークン ---------------------------------------------------------
check "JWT 形式のトークン" 'eyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{20,}'
# 接頭辞だけでは拾わない。報告書では「sb_publishable_... という鍵」のように
# 種類を説明するために接頭辞を書くことが正当にあるため、実際の鍵の長さがあるものだけを見る。
check "各種サービスの鍵" '((sk|pk)_live_[0-9A-Za-z]{12,}|AKIA[0-9A-Z]{16}|ghp_[0-9A-Za-z]{20,}|xox[baprs]-[0-9A-Za-z-]{12,}|AIza[0-9A-Za-z_-]{20,}|sb_(secret|publishable)_[0-9A-Za-z_-]{12,})'
check "接続文字列" '(postgres(ql)?|mysql|mongodb(\+srv)?|redis|amqp)://[^ \t"'"'"'`]{8,}'
check "秘密鍵ブロック" '-----BEGIN [A-Z ]*PRIVATE KEY-----'
check "key/secret への値の代入" '(api[_-]?key|secret|password|passwd|token)[[:space:]]*[:=][[:space:]]*["'"'"'`][A-Za-z0-9_/+-]{16,}' \
      "※ 説明文の中の変数名は誤検出。値が書かれていないか確認する"

# --- 個人情報 -------------------------------------------------------------
check "メールアドレス" '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}' \
      "※ example.com / example.invalid / noreply など、説明用の値なら問題ない"
check "電話番号らしき並び" '(0[0-9]{1,4}-[0-9]{1,4}-[0-9]{3,4}|\+81[0-9-]{9,})'
check "クレジットカード番号らしき並び" '\b[0-9]{4}[ -]?[0-9]{4}[ -]?[0-9]{4}[ -]?[0-9]{4}\b'
check "12 桁の数字の並び（マイナンバー等）" '\b[0-9]{4}[ -]?[0-9]{4}[ -]?[0-9]{4}\b'
# 住所は「都道府県名 + 市区町村 + 数字」まで揃ったものだけを見る。
# 文字クラス（[都道府県]）で書くと 1 文字ずつの照合になり、無関係な日本語文に大量に当たる。
# 数字まで求めるのは、「都道府県と市区町村まではマスクする」のような説明文を拾わないため。
# 全角数字は [０-９] のような範囲指定にしない。ロケールによっては
# 「Invalid collation character」で grep 全体が失敗し、検査が黙って素通りする。
# 1 文字ずつ列挙すれば、どのロケールでも同じ結果になる。
check "住所らしき記述" '(東京都|北海道|大阪府|京都府|[^ |、。＋+]{2,3}県)[^ |、。]{0,12}[市区町村郡][^ |、。]{0,16}([0-9]|[０１２３４５６７８９])'

# --- SQL の書き方 ---------------------------------------------------------
check "select * の使用" 'select[[:space:]]+\*[[:space:]]+from' \
      "※ 実データを取得しかねない。必要な列だけを指定する方針と整合しているか確認する"

# --------------------------------------------------------------------------
echo
if [[ $HITS -eq 0 ]]; then
  echo "検出なし。"
else
  echo "$HITS 種類の検出があった。上記を確認し、必要なら伏字にするか削除する。"
fi
echo
echo "注意: これはパターンマッチであり、取りこぼしも誤検出もある。"
echo "      0 件であることは「機械的に見つかる混入が無い」ことを意味するだけで、"
echo "      安全を保証しない。最終的には自分で読み返すこと。"
